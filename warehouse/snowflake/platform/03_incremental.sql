-- Northgate on Snowflake: incremental loading with Streams and Tasks.
--
-- Order lines arrive as events, in three batches, the way a source system's
-- change feed delivers them: in date order mostly, with a provisional price
-- later corrected, the same events delivered twice, lines that arrive months
-- late, test orders that are later cancelled, and one stale event older than
-- what the table already holds. A task graph applies them as they land:
--
--   INGEST.SALES_LINE_EVENTS  (append-only landing table)
--     -> stream SALES_LINE_EVENTS_STREAM
--     -> task APPLY_SALES_EVENTS          every minute, only when the stream has data:
--                                         MERGE the newest event per line into SALES_LINES_CURRENT
--     -> stream SALES_LINES_CURRENT_STREAM
--     -> task REFRESH_DAILY_REGION_SALES  after the first: recompute only the
--                                         (date, region) cells the change touched
--
-- After the last batch, SALES_LINES_CURRENT must equal SYNTHETIC_SEED.SALES_FACT
-- row for row, and DAILY_REGION_SALES must equal a full GROUP BY of it. That is
-- what 05_incremental_checks.sql and the Snowpark procedure in 06_snowpark.sql test.
-- Event sequence numbers: 10 = first delivery, 20 = correction or cancellation,
-- 5 = a stale replay of an old version that must be ignored.

ALTER SESSION SET QUERY_TAG = 'northgate:incremental-setup';
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
USE WAREHOUSE DBT_WH;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.INGEST;
USE SCHEMA NORTHGATE_DEMO.INGEST;

ALTER TASK IF EXISTS APPLY_SALES_EVENTS SUSPEND;
ALTER TASK IF EXISTS REFRESH_DAILY_REGION_SALES SUSPEND;

-- What the feed will deliver, batch by batch: the spec of the test, from the
-- real sales fact. Line ids that are multiples of 101 are first priced 10% low
-- and corrected in batch 2; multiples of 499 are delivered twice; multiples of
-- 997 dated before June arrive late, in batch 3; multiples of 1013 get a test
-- order (negative id) in batch 1 that batch 3 cancels; multiples of 1999 get a
-- stale replay at sequence 5 in batch 3.
CREATE OR REPLACE VIEW SALES_EVENT_PLAN AS
WITH lines AS (
  SELECT "OrderLineId" AS ORDER_LINE_ID, "Date" AS ORDER_DATE, "OrderId" AS ORDER_ID,
         "CustomerId" AS CUSTOMER_ID, "ProductId" AS PRODUCT_ID, "SupplierName" AS SUPPLIER_NAME,
         "RegionName" AS REGION_NAME, "Revenue" AS REVENUE, "DiscountAmount" AS DISCOUNT_AMOUNT,
         "Cost" AS COST, "QuantityShipped" AS QUANTITY_SHIPPED, "WeightLb" AS WEIGHT_LB,
         CASE WHEN "Date" < '2026-04-01' THEN 1 WHEN "Date" < '2026-06-01' THEN 2 ELSE 3 END AS NATURAL_BATCH,
         MOD("OrderLineId", 997) = 0 AND "Date" < '2026-06-01' AS ARRIVES_LATE
  FROM NORTHGATE_DEMO.SYNTHETIC_SEED.SALES_FACT
),
first_delivery AS (
  SELECT IFF(ARRIVES_LATE, 3, NATURAL_BATCH) AS BATCH_ID, 10 AS EVENT_SEQ, 'upsert' AS OP,
         ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME,
         IFF(MOD(ORDER_LINE_ID, 101) = 0 AND NOT ARRIVES_LATE AND NATURAL_BATCH = 1, REVENUE * 0.9, REVENUE) AS REVENUE,
         DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'first delivery' AS NOTE
  FROM lines
),
corrections AS (
  SELECT 2, 20, 'upsert', ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME,
         REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'price correction'
  FROM lines WHERE MOD(ORDER_LINE_ID, 101) = 0 AND NOT ARRIVES_LATE AND NATURAL_BATCH = 1
),
redelivered AS (
  SELECT 2, EVENT_SEQ, OP, ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME,
         REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'duplicate delivery'
  FROM first_delivery WHERE BATCH_ID = 1 AND MOD(ORDER_LINE_ID, 499) = 0
),
test_orders AS (
  SELECT 1, 10, 'upsert', -ORDER_LINE_ID, ORDER_DATE, 'TEST-' || ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME,
         REGION_NAME, REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'test order'
  FROM lines WHERE MOD(ORDER_LINE_ID, 1013) = 0 AND NATURAL_BATCH = 1 AND NOT ARRIVES_LATE
),
cancellations AS (
  SELECT 3, 20, 'delete', ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME,
         REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'test order cancelled'
  FROM test_orders
),
stale AS (
  SELECT 3, 5, 'upsert', ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME,
         REVENUE * 3, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, 'stale replay'
  FROM lines WHERE MOD(ORDER_LINE_ID, 1999) = 0 AND NATURAL_BATCH = 1 AND NOT ARRIVES_LATE
)
SELECT * FROM first_delivery
UNION ALL SELECT * FROM corrections
UNION ALL SELECT * FROM redelivered
UNION ALL SELECT * FROM test_orders
UNION ALL SELECT * FROM cancellations
UNION ALL SELECT * FROM stale;

CREATE OR REPLACE TABLE SALES_LINE_EVENTS (
  BATCH_ID INT, EVENT_SEQ INT, OP STRING, ORDER_LINE_ID NUMBER(38, 0), ORDER_DATE DATE, ORDER_ID STRING,
  CUSTOMER_ID STRING, PRODUCT_ID STRING, SUPPLIER_NAME STRING, REGION_NAME STRING, REVENUE FLOAT,
  DISCOUNT_AMOUNT FLOAT, COST FLOAT, QUANTITY_SHIPPED FLOAT, WEIGHT_LB FLOAT, NOTE STRING,
  LANDED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

CREATE OR REPLACE TABLE SALES_LINES_CURRENT (
  ORDER_LINE_ID NUMBER(38, 0) PRIMARY KEY, ORDER_DATE DATE, ORDER_ID STRING, CUSTOMER_ID STRING, PRODUCT_ID STRING,
  SUPPLIER_NAME STRING, REGION_NAME STRING, REVENUE FLOAT, DISCOUNT_AMOUNT FLOAT, COST FLOAT,
  QUANTITY_SHIPPED FLOAT, WEIGHT_LB FLOAT, EVENT_SEQ INT, APPLIED_AT TIMESTAMP_LTZ);

CREATE OR REPLACE TABLE DAILY_REGION_SALES (
  ORDER_DATE DATE, REGION_NAME STRING, ORDER_LINES INT, REVENUE NUMBER(38, 6), COST NUMBER(38, 6),
  DISCOUNT_AMOUNT NUMBER(38, 6), REFRESHED_AT TIMESTAMP_LTZ);

CREATE OR REPLACE STREAM SALES_LINE_EVENTS_STREAM ON TABLE SALES_LINE_EVENTS APPEND_ONLY = TRUE;
CREATE OR REPLACE STREAM SALES_LINES_CURRENT_STREAM ON TABLE SALES_LINES_CURRENT;

CREATE OR REPLACE TASK APPLY_SALES_EVENTS
  WAREHOUSE = DBT_WH
  SCHEDULE = '1 MINUTE'
  QUERY_TAG = 'northgate:incremental-apply'
  WHEN SYSTEM$STREAM_HAS_DATA('NORTHGATE_DEMO.INGEST.SALES_LINE_EVENTS_STREAM')
AS
MERGE INTO NORTHGATE_DEMO.INGEST.SALES_LINES_CURRENT t
USING (
  SELECT * FROM NORTHGATE_DEMO.INGEST.SALES_LINE_EVENTS_STREAM
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ORDER_LINE_ID
                             ORDER BY EVENT_SEQ DESC, IFF(OP = 'delete', 0, 1), LANDED_AT DESC) = 1
) s
ON t.ORDER_LINE_ID = s.ORDER_LINE_ID
WHEN MATCHED AND s.OP = 'delete' AND s.EVENT_SEQ >= t.EVENT_SEQ THEN DELETE
WHEN MATCHED AND s.OP = 'upsert' AND s.EVENT_SEQ > t.EVENT_SEQ THEN UPDATE SET
  ORDER_DATE = s.ORDER_DATE, ORDER_ID = s.ORDER_ID, CUSTOMER_ID = s.CUSTOMER_ID, PRODUCT_ID = s.PRODUCT_ID,
  SUPPLIER_NAME = s.SUPPLIER_NAME, REGION_NAME = s.REGION_NAME, REVENUE = s.REVENUE,
  DISCOUNT_AMOUNT = s.DISCOUNT_AMOUNT, COST = s.COST, QUANTITY_SHIPPED = s.QUANTITY_SHIPPED,
  WEIGHT_LB = s.WEIGHT_LB, EVENT_SEQ = s.EVENT_SEQ, APPLIED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED AND s.OP = 'upsert' THEN INSERT
  (ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME, REGION_NAME, REVENUE,
   DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, EVENT_SEQ, APPLIED_AT)
  VALUES (s.ORDER_LINE_ID, s.ORDER_DATE, s.ORDER_ID, s.CUSTOMER_ID, s.PRODUCT_ID, s.SUPPLIER_NAME, s.REGION_NAME,
          s.REVENUE, s.DISCOUNT_AMOUNT, s.COST, s.QUANTITY_SHIPPED, s.WEIGHT_LB, s.EVENT_SEQ, CURRENT_TIMESTAMP());

CREATE OR REPLACE TASK REFRESH_DAILY_REGION_SALES
  WAREHOUSE = DBT_WH
  QUERY_TAG = 'northgate:incremental-refresh'
  AFTER APPLY_SALES_EVENTS
AS
MERGE INTO NORTHGATE_DEMO.INGEST.DAILY_REGION_SALES d
USING (
  WITH touched AS (
    SELECT DISTINCT ORDER_DATE, REGION_NAME FROM NORTHGATE_DEMO.INGEST.SALES_LINES_CURRENT_STREAM
  ),
  fresh AS (
    SELECT c.ORDER_DATE, c.REGION_NAME, COUNT(*) AS ORDER_LINES,
           SUM(c.REVENUE::NUMBER(18, 6)) AS REVENUE, SUM(c.COST::NUMBER(18, 6)) AS COST,
           SUM(c.DISCOUNT_AMOUNT::NUMBER(18, 6)) AS DISCOUNT_AMOUNT
    FROM NORTHGATE_DEMO.INGEST.SALES_LINES_CURRENT c
    JOIN touched t ON t.ORDER_DATE = c.ORDER_DATE AND t.REGION_NAME = c.REGION_NAME
    GROUP BY c.ORDER_DATE, c.REGION_NAME
  )
  SELECT t.ORDER_DATE, t.REGION_NAME, f.ORDER_LINES, f.REVENUE, f.COST, f.DISCOUNT_AMOUNT
  FROM touched t
  LEFT JOIN fresh f ON f.ORDER_DATE = t.ORDER_DATE AND f.REGION_NAME = t.REGION_NAME
) s
ON d.ORDER_DATE = s.ORDER_DATE AND d.REGION_NAME = s.REGION_NAME
WHEN MATCHED AND s.ORDER_LINES IS NULL THEN DELETE
WHEN MATCHED THEN UPDATE SET ORDER_LINES = s.ORDER_LINES, REVENUE = s.REVENUE, COST = s.COST,
  DISCOUNT_AMOUNT = s.DISCOUNT_AMOUNT, REFRESHED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED AND s.ORDER_LINES IS NOT NULL THEN INSERT
  (ORDER_DATE, REGION_NAME, ORDER_LINES, REVENUE, COST, DISCOUNT_AMOUNT, REFRESHED_AT)
  VALUES (s.ORDER_DATE, s.REGION_NAME, s.ORDER_LINES, s.REVENUE, s.COST, s.DISCOUNT_AMOUNT, CURRENT_TIMESTAMP());

-- Children first, then the root: the graph starts running on its schedule.
ALTER TASK REFRESH_DAILY_REGION_SALES RESUME;
ALTER TASK APPLY_SALES_EVENTS RESUME;

SELECT BATCH_ID, NOTE, COUNT(*) AS EVENTS FROM SALES_EVENT_PLAN GROUP BY 1, 2 ORDER BY 1, 2;
