-- Northgate on Snowflake: who may touch what.
--
-- Two layers, the pattern Snowflake recommends. Access roles are database roles
-- inside NORTHGATE_DEMO and hold the privileges. Functional roles are account
-- roles that people and services are given; they hold nothing but access roles
-- and the warehouse. All three functional roles roll up to SYSADMIN, so the
-- administrator inherits everything and nothing is orphaned.
--
--   NORTHGATE_LOADER       lands raw data              RAW_WRITE
--   NORTHGATE_TRANSFORMER  builds the dbt models       RAW_READ + MODEL_WRITE
--   NORTHGATE_ANALYST      reads the marts, nothing else  MART_READ
--
-- Future grants mean a table dbt creates tomorrow is readable by the right roles
-- without anyone remembering to grant it. 02_access_checks.sql then tries every
-- action as every role and records what Snowflake allowed.

ALTER SESSION SET QUERY_TAG = 'northgate:access';

USE ROLE SYSADMIN;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.INGEST;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.PLATFORM;

-- Access roles (database roles: they live and travel with the database).
CREATE DATABASE ROLE IF NOT EXISTS NORTHGATE_DEMO.RAW_READ;
CREATE DATABASE ROLE IF NOT EXISTS NORTHGATE_DEMO.RAW_WRITE;
CREATE DATABASE ROLE IF NOT EXISTS NORTHGATE_DEMO.MODEL_READ;
CREATE DATABASE ROLE IF NOT EXISTS NORTHGATE_DEMO.MODEL_WRITE;
CREATE DATABASE ROLE IF NOT EXISTS NORTHGATE_DEMO.MART_READ;
GRANT DATABASE ROLE NORTHGATE_DEMO.RAW_READ TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT DATABASE ROLE NORTHGATE_DEMO.MODEL_READ TO DATABASE ROLE NORTHGATE_DEMO.MODEL_WRITE;

-- Functional roles, created by USERADMIN and placed under SYSADMIN.
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS NORTHGATE_LOADER COMMENT = 'Lands raw data into NORTHGATE_DEMO raw schemas';
CREATE ROLE IF NOT EXISTS NORTHGATE_TRANSFORMER COMMENT = 'Reads raw, builds the dbt staging and mart models';
CREATE ROLE IF NOT EXISTS NORTHGATE_ANALYST COMMENT = 'Reads the marts only';
GRANT ROLE NORTHGATE_LOADER TO ROLE SYSADMIN;
GRANT ROLE NORTHGATE_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE NORTHGATE_ANALYST TO ROLE SYSADMIN;

-- Privileges go to access roles only. SECURITYADMIN holds MANAGE GRANTS,
-- which future grants need.
USE ROLE SECURITYADMIN;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;

-- Raw: the three landing schemas.
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_READ;

GRANT CREATE TABLE ON SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT CREATE TABLE ON SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT CREATE TABLE ON SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.SYNTHETIC_SEED TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.RETURNS_APP TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;
GRANT INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.INGEST TO DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE;

-- Models: dbt's staging and mart schemas.
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_READ;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA NORTHGATE_DEMO.DBT_STAGING TO DATABASE ROLE NORTHGATE_DEMO.MODEL_WRITE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MODEL_WRITE;

-- Marts only, for analysts and BI tools.
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;
GRANT SELECT ON ALL TABLES IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;
GRANT SELECT ON ALL VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA NORTHGATE_DEMO.DBT_ANALYTICS TO DATABASE ROLE NORTHGATE_DEMO.MART_READ;

-- Functional roles get access roles and the warehouse, nothing else.
GRANT DATABASE ROLE NORTHGATE_DEMO.RAW_WRITE TO ROLE NORTHGATE_LOADER;
GRANT DATABASE ROLE NORTHGATE_DEMO.RAW_READ TO ROLE NORTHGATE_TRANSFORMER;
GRANT DATABASE ROLE NORTHGATE_DEMO.MODEL_WRITE TO ROLE NORTHGATE_TRANSFORMER;
GRANT DATABASE ROLE NORTHGATE_DEMO.MART_READ TO ROLE NORTHGATE_ANALYST;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE NORTHGATE_LOADER;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE NORTHGATE_TRANSFORMER;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE NORTHGATE_ANALYST;

-- The probe that 02_access_checks.sql calls as each role. It runs with the
-- caller's rights, so Snowflake judges the caller, and it writes one row per
-- attempt to PLATFORM.ACCESS_CHECKS (the only thing all three roles may write).
USE ROLE SYSADMIN;
CREATE TABLE IF NOT EXISTS NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS (
  CHECKED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  ROLE_NAME STRING, ACTION STRING, OBJECT_NAME STRING, OUTCOME STRING, DETAIL STRING);
CREATE OR REPLACE PROCEDURE NORTHGATE_DEMO.PLATFORM.TRY_ACCESS(
    ACTION STRING, OBJECT_NAME STRING, STATEMENT STRING, CLEANUP STRING)
  RETURNS STRING
  LANGUAGE SQL
  EXECUTE AS CALLER
AS
$$
DECLARE
  outcome STRING DEFAULT 'allowed';
  detail STRING DEFAULT '';
BEGIN
  BEGIN
    EXECUTE IMMEDIATE :STATEMENT;
    IF (CLEANUP <> '') THEN
      EXECUTE IMMEDIATE :CLEANUP;
    END IF;
  EXCEPTION
    WHEN OTHER THEN
      outcome := 'denied';
      detail := LEFT(SQLERRM, 200);
  END;
  INSERT INTO NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS (ROLE_NAME, ACTION, OBJECT_NAME, OUTCOME, DETAIL)
    SELECT CURRENT_ROLE(), :ACTION, :OBJECT_NAME, :outcome, :detail;
  RETURN outcome;
END;
$$;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.PLATFORM TO ROLE NORTHGATE_LOADER;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.PLATFORM TO ROLE NORTHGATE_TRANSFORMER;
GRANT USAGE ON SCHEMA NORTHGATE_DEMO.PLATFORM TO ROLE NORTHGATE_ANALYST;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO ROLE NORTHGATE_LOADER;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO ROLE NORTHGATE_TRANSFORMER;
GRANT USAGE ON DATABASE NORTHGATE_DEMO TO ROLE NORTHGATE_ANALYST;
GRANT USAGE ON PROCEDURE NORTHGATE_DEMO.PLATFORM.TRY_ACCESS(STRING, STRING, STRING, STRING) TO ROLE NORTHGATE_LOADER;
GRANT USAGE ON PROCEDURE NORTHGATE_DEMO.PLATFORM.TRY_ACCESS(STRING, STRING, STRING, STRING) TO ROLE NORTHGATE_TRANSFORMER;
GRANT USAGE ON PROCEDURE NORTHGATE_DEMO.PLATFORM.TRY_ACCESS(STRING, STRING, STRING, STRING) TO ROLE NORTHGATE_ANALYST;
GRANT INSERT ON TABLE NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS TO ROLE NORTHGATE_LOADER;
GRANT INSERT ON TABLE NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS TO ROLE NORTHGATE_TRANSFORMER;
GRANT INSERT ON TABLE NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS TO ROLE NORTHGATE_ANALYST;
TRUNCATE TABLE NORTHGATE_DEMO.PLATFORM.ACCESS_CHECKS;

SELECT 'access roles in place' AS STATUS;
