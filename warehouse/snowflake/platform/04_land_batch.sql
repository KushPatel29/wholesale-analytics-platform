--     USING (batch => 1);
-- then let the task graph pick it up on its next scheduled run (within a minute).
ALTER SESSION SET QUERY_TAG = 'northgate:incremental-land';
USE ROLE SYSADMIN;
USE WAREHOUSE DBT_WH;
INSERT INTO NORTHGATE_DEMO.INGEST.SALES_LINE_EVENTS
  (BATCH_ID, EVENT_SEQ, OP, ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME,
   REGION_NAME, REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, NOTE)
SELECT BATCH_ID, EVENT_SEQ, OP, ORDER_LINE_ID, ORDER_DATE, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, SUPPLIER_NAME,
       REGION_NAME, REVENUE, DISCOUNT_AMOUNT, COST, QUANTITY_SHIPPED, WEIGHT_LB, NOTE
FROM NORTHGATE_DEMO.INGEST.SALES_EVENT_PLAN
WHERE BATCH_ID = {{ batch }}
-- Within a batch the feed is not in order: shuffle it the same way every run.
ORDER BY HASH(ORDER_LINE_ID, EVENT_SEQ, NOTE);
SELECT {{ batch }} AS BATCH_LANDED, COUNT(*) AS EVENTS
FROM NORTHGATE_DEMO.INGEST.SALES_LINE_EVENTS WHERE BATCH_ID = {{ batch }};
