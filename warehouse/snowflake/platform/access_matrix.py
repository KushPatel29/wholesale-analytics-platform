"""The access design for Northgate on Snowflake, as data.

ACTIONS is every attempt 02_access_checks.sql makes; EXPECTED says which roles
the design allows for each. `python -m warehouse.snowflake.platform.access_matrix`
writes 02_access_checks.sql from this file, and tests/test_snowflake_platform.py
holds the recorded outcomes (evidence.json) to EXPECTED cell by cell.
"""
from __future__ import annotations

from pathlib import Path

ROLES = ["NORTHGATE_LOADER", "NORTHGATE_TRANSFORMER", "NORTHGATE_ANALYST", "SYSADMIN"]
DB = "NORTHGATE_DEMO"

# (action, object, statement, cleanup, roles allowed)
ACTIONS: list[tuple[str, str, str, str, set[str]]] = [
    ("select", "raw SYNTHETIC_SEED.SALES_FACT",
     f"SELECT COUNT(*) FROM {DB}.SYNTHETIC_SEED.SALES_FACT", "",
     {"NORTHGATE_LOADER", "NORTHGATE_TRANSFORMER", "SYSADMIN"}),
    ("insert", "raw SYNTHETIC_SEED.FINANCE_MONTH",
     f"INSERT INTO {DB}.SYNTHETIC_SEED.FINANCE_MONTH SELECT * FROM {DB}.SYNTHETIC_SEED.FINANCE_MONTH WHERE FALSE", "",
     {"NORTHGATE_LOADER", "SYSADMIN"}),
    ("create table", "raw schema INGEST",
     f"CREATE TRANSIENT TABLE {DB}.INGEST.ACCESS_PROBE (X INT)", f"DROP TABLE {DB}.INGEST.ACCESS_PROBE",
     {"NORTHGATE_LOADER", "SYSADMIN"}),
    ("select", "raw INGEST.SALES_LINES_CURRENT (created after the grants)",
     f"SELECT COUNT(*) FROM {DB}.INGEST.SALES_LINES_CURRENT", "",
     {"NORTHGATE_LOADER", "NORTHGATE_TRANSFORMER", "SYSADMIN"}),
    ("select", "staging DBT_STAGING.STG_SALES_FACT",
     f"SELECT COUNT(*) FROM {DB}.DBT_STAGING.STG_SALES_FACT", "",
     {"NORTHGATE_TRANSFORMER", "SYSADMIN"}),
    ("create table", "model schema DBT_STAGING",
     f"CREATE TRANSIENT TABLE {DB}.DBT_STAGING.ACCESS_PROBE (X INT)", f"DROP TABLE {DB}.DBT_STAGING.ACCESS_PROBE",
     {"NORTHGATE_TRANSFORMER", "SYSADMIN"}),
    ("select", "mart DBT_ANALYTICS.FCT_COMMERCIAL_PERFORMANCE (rebuilt by dbt after the grants)",
     f"SELECT COUNT(*) FROM {DB}.DBT_ANALYTICS.FCT_COMMERCIAL_PERFORMANCE", "",
     {"NORTHGATE_TRANSFORMER", "NORTHGATE_ANALYST", "SYSADMIN"}),
    ("delete", "mart DBT_ANALYTICS.FCT_COMMERCIAL_PERFORMANCE",
     f"DELETE FROM {DB}.DBT_ANALYTICS.FCT_COMMERCIAL_PERFORMANCE WHERE FALSE", "",
     {"SYSADMIN"}),
    ("select", "account usage SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY",
     "SELECT COUNT(*) FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY WHERE FALSE", "",
     set()),
]

EXPECTED = {(role, action, obj): ("allowed" if role in allowed else "denied")
            for action, obj, _, _, allowed in ACTIONS for role in ROLES}


def _q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def render() -> str:
    lines = [
        "-- Generated by warehouse/snowflake/platform/access_matrix.py; do not edit by hand.",
        "-- Every action, tried as every role, through PLATFORM.TRY_ACCESS (caller's rights).",
        "-- Each attempt writes one row to PLATFORM.ACCESS_CHECKS; the last statement returns them.",
        "",
        "ALTER SESSION SET QUERY_TAG = 'northgate:access-checks';",
        "USE ROLE SYSADMIN;",
        f"TRUNCATE TABLE {DB}.PLATFORM.ACCESS_CHECKS;",
    ]
    for role in ROLES:
        lines += ["", f"USE ROLE {role};", "USE WAREHOUSE DBT_WH;"]
        for action, obj, stmt, cleanup, _ in ACTIONS:
            lines.append(f"CALL {DB}.PLATFORM.TRY_ACCESS({_q(action)}, {_q(obj)}, {_q(stmt)}, {_q(cleanup)});")
    lines += [
        "",
        "USE ROLE SYSADMIN;",
        "SELECT ARRAY_AGG(OBJECT_CONSTRUCT('role', ROLE_NAME, 'action', ACTION, 'object', OBJECT_NAME,",
        "                                  'outcome', OUTCOME, 'detail', DETAIL))",
        "         WITHIN GROUP (ORDER BY ROLE_NAME, ACTION, OBJECT_NAME) AS ACCESS_CHECKS",
        f"FROM {DB}.PLATFORM.ACCESS_CHECKS;",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    out = Path(__file__).with_name("02_access_checks.sql")
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")
