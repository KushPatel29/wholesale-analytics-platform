-- Load Northgate's landed sources into Snowflake and run the dbt project there,
-- with dbt Projects on Snowflake. Run it in a Snowsight SQL file. No credential
-- appears: the repository is public and the project runs as the signed-in user.
--
-- Prerequisite, once per account (ACCOUNTADMIN), shared with the other projects:
--   CREATE API INTEGRATION GITHUB_KUSHPATEL29 API_PROVIDER = git_https_api
--     API_ALLOWED_PREFIXES = ('https://github.com/KushPatel29/') ENABLED = TRUE;
--   GRANT USAGE ON INTEGRATION GITHUB_KUSHPATEL29 TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS DBT_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE DBT_WH;
CREATE DATABASE IF NOT EXISTS NORTHGATE_DEMO;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.DEPLOY;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.SYNTHETIC_SEED;
CREATE SCHEMA IF NOT EXISTS NORTHGATE_DEMO.RETURNS_APP;

-- 1. The repository, and the landed Parquet copied from it into an internal stage.
CREATE GIT REPOSITORY IF NOT EXISTS NORTHGATE_DEMO.DEPLOY.WHOLESALE_ANALYTICS_PLATFORM
  API_INTEGRATION = GITHUB_KUSHPATEL29
  ORIGIN = 'https://github.com/KushPatel29/wholesale-analytics-platform.git';
ALTER GIT REPOSITORY NORTHGATE_DEMO.DEPLOY.WHOLESALE_ANALYTICS_PLATFORM FETCH;
CREATE STAGE IF NOT EXISTS NORTHGATE_DEMO.DEPLOY.LANDING;
CREATE FILE FORMAT IF NOT EXISTS NORTHGATE_DEMO.DEPLOY.PARQUET TYPE = PARQUET;
COPY FILES INTO @NORTHGATE_DEMO.DEPLOY.LANDING
  FROM @NORTHGATE_DEMO.DEPLOY.WHOLESALE_ANALYTICS_PLATFORM/branches/main/warehouse/landing/;

-- 2. One raw table per source, its schema inferred from the Parquet, then loaded.
--    sales_fact keeps the source system's PascalCase (the staging model quotes it).

CREATE OR REPLACE TABLE NORTHGATE_DEMO.SYNTHETIC_SEED.SALES_FACT USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT(*)) WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@NORTHGATE_DEMO.DEPLOY.LANDING/sales_fact/', FILE_FORMAT => 'NORTHGATE_DEMO.DEPLOY.PARQUET')));
COPY INTO NORTHGATE_DEMO.SYNTHETIC_SEED.SALES_FACT FROM @NORTHGATE_DEMO.DEPLOY.LANDING/sales_fact/
  FILE_FORMAT = (FORMAT_NAME = 'NORTHGATE_DEMO.DEPLOY.PARQUET') MATCH_BY_COLUMN_NAME = CASE_SENSITIVE;

