-- 3. Deploy the dbt project from the same repository and build it.
CREATE OR REPLACE DBT PROJECT NORTHGATE_DEMO.DEPLOY.NORTHGATE_RETAIL_ANALYTICS
  FROM '@NORTHGATE_DEMO.DEPLOY.WHOLESALE_ANALYTICS_PLATFORM/branches/main'
  DBT_VERSION = '1.11.11'
  DEFAULT_TARGET = 'snowflake';
EXECUTE DBT PROJECT NORTHGATE_DEMO.DEPLOY.NORTHGATE_RETAIL_ANALYTICS
  ARGS = 'build --target snowflake';

